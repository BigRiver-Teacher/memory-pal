import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

const pageUrl = new URL("../src/app/page.tsx", import.meta.url);
const layoutUrl = new URL("../src/app/layout.tsx", import.meta.url);
const pageSource = await readFile(pageUrl, "utf8");
const layoutSource = await readFile(layoutUrl, "utf8");

test("root page redirects visitors to the login page", () => {
  assert.match(
    pageSource,
    /import \{ redirect \} from "next\/navigation"/,
  );
  assert.match(pageSource, /redirect\("\/login"\)/);
});

test("root page no longer ships the create-next-app scaffold", () => {
  assert.ok(!pageSource.includes("next/image"));
  assert.ok(!pageSource.includes("To get started, edit the"));
  assert.ok(!pageSource.includes("Deploy Now"));
  assert.ok(!pageSource.includes("vercel.com/new"));
});

test("root layout metadata is branded instead of the scaffold default", () => {
  assert.ok(!layoutSource.includes("Create Next App"));
  assert.ok(!layoutSource.includes("Generated by create next app"));
  assert.match(layoutSource, /title: "忆伴/);
  assert.match(layoutSource, /lang="zh-CN"/);
});
